/**
 * `bun scripts/db-generate.ts [dir]`: runs `drizzle-kit generate` here (or in `dir`), then bundles the
 * SQL it wrote into `<out>/index.ts`, because Workers have no filesystem to read migrations from.
 * Statements are made idempotent (`IF NOT EXISTS`), so the first migration is a no-op on a database
 * that predates migrations.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const dir = resolve(process.argv[2] ?? ".");
const config = (await import(join(dir, "drizzle.config.ts"))).default as { out: string };
const out = resolve(dir, config.out);

const generated = Bun.spawnSync(["bunx", "drizzle-kit", "generate"], { cwd: dir, stdout: "inherit", stderr: "inherit" });
if(generated.exitCode !== 0) process.exit(generated.exitCode);

function idempotent(statement: string): string {
  return statement
    .replace(/^CREATE TABLE (?!IF NOT EXISTS)/i, "CREATE TABLE IF NOT EXISTS ")
    .replace(/^CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)/i, "CREATE $1INDEX IF NOT EXISTS ");
}

const migrations = readdirSync(out).filter(name => name.endsWith(".sql")).sort().map(name => ({
  tag: name.replace(/\.sql$/, ""),
  statements: readFileSync(join(out, name), "utf8").split("--> statement-breakpoint").map(s => idempotent(s.trim())).filter(Boolean)
}));

writeFileSync(join(out, "index.ts"), `// Generated by scripts/db-generate.ts. Do not edit.
import type { Migration } from "vibe-cms/db";

export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2).replace(/^(\s*)"(tag|statements)":/gm, "$1$2:")};
`);
console.log(`Bundled ${migrations.length} migration(s) into ${join(out, "index.ts")}`);
